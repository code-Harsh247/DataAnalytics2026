"""Run every analysis and write analysis/REPORT.md (numbers come from the
result files, never typed by hand).

    python -m analysis.run_all            # run everything, then write the report
    python -m analysis.run_all --report   # only rewrite the report from analysis/out/*.json
"""

import argparse
import json

from .common import MODEL_LABELS, MODEL_ORDER, OUT, ROOT


def load(name: str) -> dict:
    return json.loads((OUT / f"{name}.json").read_text())


def pct(x, digits=0) -> str:
    return "—" if x is None else f"{x * 100:.{digits}f}%"


def report() -> str:
    eda, stats, sens, fc = load("eda"), load("model_stats"), load("sensitivity"), load("forecast_skill")
    p, t = eda["profile"], eda["temperature_coefficient"]
    boot, paired, eps, sev = stats["bootstrap"], stats["paired"], stats["episodes"], stats["severity"]
    lines = []
    w = lines.append

    w("# Analytics report")
    w("")
    w("*Generated by `python -m analysis.run_all` (from `webapp/backend`). Every number below is read from "
      "`analysis/out/*.json`; rerun to reproduce. Context and decisions: `FINDINGS.md`.*")
    w("")
    w("**Data.** The benchmark is the canonical dataset (`data/backfill/sample_plant.csv`): 30 days of real "
      "ERA5 weather at 18°N 80°E through the plant's physics model, 4 inverters, injected and labelled "
      "faults. Detection results pool seeds 1–8 (same weather, different noise and faults), test window = "
      "last 30% of hours, daylight only. The forecast study uses 12 months of real weather at the test plant.")
    w("")

    # 1 ---------------------------------------------------------------- data
    w("## 1. The data")
    w("")
    w(f"| Rows | Inverters | Hours | Daylight | Faulted daylight hours | Missing values |")
    w("|---|---|---|---|---|---|")
    w(f"| {p['rows']:,} | {p['inverters']} | {p['hours']} | {pct(p['daylight_share'])} | "
      f"{pct(p['faulted_daylight_share'], 1)} | {p['missing_values']} |")
    w("")
    w(f"![Daily profile]({eda['figures']['daily_profile']}) ![Power vs irradiance]({eda['figures']['power_vs_irradiance']})")
    w("")
    w("- Output tracks sunlight on the panels almost linearly; the spread at a given irradiance is "
      "temperature (hotter = lower), noise, shading and faults.")
    w(f"- **The temperature effect, recovered from the data:** a regression of efficiency on cell temperature "
      f"over {t['rows']} bright, healthy hours gives **{t['coefficient_per_c'] * 100:.2f}%/°C**, against the "
      f"{t['configured'] * 100:.2f}%/°C the simulator was configured with. The difference is sampling noise, "
      f"not bias: the day-block bootstrap 95% CI is {t['ci95'][0] * 100:.2f} to {t['ci95'][1] * 100:.2f}%/°C "
      f"(it contains the true value), and across seeds 1–8 the estimate averages {t['seeds_1_8_mean'] * 100:.2f}%/°C. "
      "The method works; one month of one plant pins the coefficient down to about ±0.1%/°C.")
    w("")
    w(f"![Temperature effect]({eda['figures']['temperature_effect']}) ![Correlations]({eda['figures']['correlations']})")
    w("")
    w("- **Caveat from the correlations:** cell temperature correlates ~1.0 with irradiance because the "
      "simulator derives it from irradiance (NOCT model); on a real plant they'd separate more.")
    w("")

    # 2 ---------------------------------------------------------------- model
    w("## 2. Inside the expected-power model (Random Forest)")
    w("")
    imp = eda["feature_importance_r2_drop"]
    top = list(imp.items())
    w(f"![Feature importance]({eda['figures']['feature_importance']}) ![Residuals]({eda['figures']['residuals']})")
    w("")
    w(f"- **It relies almost entirely on the neighbouring inverters.** Shuffling `peer_median_kw` drops R² "
      f"by {top[0][1]:.2f}; every weather input by less than {max(v for k, v in top[1:]):.3f}. With the peers known, "
      "weather adds little. That's why a plain peer comparison scores as well (FINDINGS §5), and why "
      "plant-wide faults (every inverter down together) are its blind spot.")
    r = eda["residuals"]
    w(f"- Healthy hours' relative shortfall: median {r['healthy_median']:.3f}, 95th percentile "
      f"{r['healthy_p95']:.3f}. Faulted hours: median {r['faulted_median']:.3f}. The label-free threshold "
      f"(~{eda['rf_threshold_seed42']:.2f}) sits just above the healthy 95th percentile; the overlap below it "
      "is where mild faults are missed.")
    w("")

    # 3 ---------------------------------------------------------------- uncertainty
    w("## 3. How sure are the model rankings?")
    w("")
    w(f"95% confidence intervals from a **day-block bootstrap** ({boot['n_blocks']} seed-days resampled "
      "2,000 times; hours within a day are correlated, so whole days are resampled).")
    w("")
    w("| Model | F1 (pooled) | 95% CI | RF − model | 95% CI of the difference | Wilcoxon p (8 seeds) |")
    w("|---|---|---|---|---|---|")
    for m in MODEL_ORDER:
        b = boot["models"][m]
        if m == "random_forest":
            w(f"| {MODEL_LABELS[m]} | **{b['f1']:.3f}** | {b['ci95'][0]:.3f}–{b['ci95'][1]:.3f} | — | — | — |")
        else:
            d, wt = boot["differences_vs_rf"][m], paired["wilcoxon_vs_rf"][m]
            sig = " ✓" if d["ci95"][0] > 0 else ""
            w(f"| {MODEL_LABELS[m]} | {b['f1']:.3f} | {b['ci95'][0]:.3f}–{b['ci95'][1]:.3f} | "
              f"{d['diff']:+.3f} | {d['ci95'][0]:+.3f} to {d['ci95'][1]:+.3f}{sig} | {wt['p_value']:.3f} |")
    w("")
    w(f"![F1 with confidence intervals]({stats['figures']['f1_ci']})")
    w("")
    w("- **Random Forest beats the physics baseline and Isolation Forest** (the bootstrap CI of the difference "
      "excludes 0, marked ✓). **It does not significantly beat Gradient Boosting**: the CI crosses 0.")
    w("- The per-seed Wilcoxon test finds nothing significant at 5%. With 8 seeds its smallest possible "
      "p-value is 0.008 and it ignores how many hours each seed holds, so it's underpowered here; the "
      "day-block bootstrap uses the hours and is the better test. More seeds would settle RF vs GB.")
    w("")

    # 4 ---------------------------------------------------------------- episodes
    w("## 4. Episodes, not hours")
    w("")
    w("An owner cares whether a fault was *noticed*, not what share of its hours were flagged. Over the "
      f"{eps['random_forest']['episodes']} fault episodes in the pooled test windows:")
    w("")
    w("| Model | Episodes caught | Alarm runs | False alarm runs | Episode precision | Caught within 1 h |")
    w("|---|---|---|---|---|---|")
    for m in MODEL_ORDER:
        e = eps[m]
        w(f"| {MODEL_LABELS[m]} | {e['caught']}/{e['episodes']} ({pct(e['episode_recall'])}) | {e['alarm_runs']} | "
          f"{e['false_alarm_runs']} | {pct(e['episode_precision'])} | {pct(e['detected_within_1h'])} |")
    w("")
    w(f"![Time to detect]({stats['figures']['time_to_detect']})")
    w("")
    b, rf = eps["baseline_ratio"], eps["random_forest"]
    w(f"- **Per-hour F1 hid a trade-off.** The physics baseline notices the most episodes ({pct(b['episode_recall'])}) "
      f"but {b['false_alarm_runs']} of its {b['alarm_runs']} alarms are false ({pct(1 - b['episode_precision'])}). "
      f"Random Forest notices {pct(rf['episode_recall'])} with {pct(rf['episode_precision'])} of alarms real: "
      "fewer catches, far fewer wild-goose chases.")
    w("- Caught faults are flagged almost immediately (median 0 daylight hours). That's partly the "
      "*centred* smoothing in the retrospective analysis, which looks one hour ahead; the live verdict uses a "
      "trailing window and is slower (FINDINGS §2).")
    w("")

    # 5 ---------------------------------------------------------------- limits
    w("## 5. The detection limit, and how it depends on the simulator")
    w("")
    w(f"![Recall by severity]({sev and stats['figures']['recall_by_severity']})")
    w("")
    w("| Severity | " + " | ".join(sev["bins"]) + " |")
    w("|---|" + "---|" * len(sev["bins"]))
    w("| Faulted hours (pooled) | " + " | ".join(str(x) for x in sev["hours_per_bin"]) + " |")
    for m in MODEL_ORDER:
        w(f"| {MODEL_LABELS[m]}, hourly recall | " + " | ".join(pct(x) for x in sev["hourly_recall"][m]) + " |")
    w("")
    rfr = sev["hourly_recall"]["random_forest"]
    w(f"- **The limit, as a curve:** Random Forest catches {pct(rfr[0])} of hours with 5–10% losses, "
      f"{pct(rfr[1])} at 10–15%, and {pct(rfr[3])}+ above 20%.")
    w("")
    w(f"![Noise sensitivity]({sens['figure']})")
    w("")
    for setting, label in [("NOISE_STD", "Measurement noise"), ("SITE_IRRADIANCE_ERROR_STD", "Site sunlight error")]:
        levels = list(sens["f1"][setting]["random_forest"].keys())
        w(f"| {label} | " + " | ".join(f"{float(x) * 100:.0f}%" for x in levels) + " |")
        w("|---|" + "---|" * len(levels))
        for m in MODEL_ORDER:
            w(f"| {MODEL_LABELS[m]} | " + " | ".join(f"{v:.3f}" for v in sens["f1"][setting][m].values()) + " |")
        w("")
    site = sens["f1"]["SITE_IRRADIANCE_ERROR_STD"]
    noise = sens["f1"]["NOISE_STD"]
    s_levels, n_levels = list(site["random_forest"]), list(noise["random_forest"])
    w(f"- **Sky error is what separates the methods.** As the plant-wide gap between reported and real "
      f"sunlight grows from {float(s_levels[0]) * 100:.0f}% to {float(s_levels[-1]) * 100:.0f}%, the physics "
      f"baseline falls from {site['baseline_ratio'][s_levels[0]]:.2f} to {site['baseline_ratio'][s_levels[-1]]:.2f} "
      f"F1, while Random Forest only goes {site['random_forest'][s_levels[0]]:.2f} → "
      f"{site['random_forest'][s_levels[-1]]:.2f}: comparing with neighbouring inverters cancels an error they "
      f"all share. With an on-site irradiance sensor (little sky error) the simple baseline would be competitive.")
    w(f"- **Measurement noise hurts every method.** From {float(n_levels[0]) * 100:.0f}% to "
      f"{float(n_levels[-1]) * 100:.0f}% noise, Random Forest drops {noise['random_forest'][n_levels[0]]:.2f} → "
      f"{noise['random_forest'][n_levels[-1]]:.2f} and stays on top.")
    w("- So the headline F1 numbers are properties of the simulator's settings as much as of the models; "
      "the *ranking* is robust to measurement noise but depends on how much the reported weather can be trusted.")
    w("")

    # 6 ---------------------------------------------------------------- forecast
    w("## 6. Is the forecast any good?")
    w("")
    a, mo, dr = fc["all"], fc["monsoon"], fc["dry"]
    w(f"{fc['days']} days ({fc['from']} to {fc['to']}) at the test plant, daily energy. *Actual* = the "
      "plant's physics on ERA5 reanalysis weather; *forecast* = the same physics on the forecast as issued "
      "the day before. Skill = 1 − MAE / MAE of the reference.")
    w("")
    w("| | Forecast MAE | Forecast error | Persistence MAE | Climatology MAE | Skill vs persistence | Skill vs climatology |")
    w("|---|---|---|---|---|---|---|")
    for name, s in [("Whole year", a), (f"Monsoon (Jun–Sep, {fc['monsoon_days']} d)", mo), ("Rest of year", dr)]:
        w(f"| {name} | {s['forecast']['mae_kwh']:.2f} kWh | {s['forecast']['mape_pct']:.1f}% | "
          f"{s['persistence']['mae_kwh']:.2f} kWh | {s['climatology']['mae_kwh']:.2f} kWh | "
          f"**{pct(s['forecast']['skill_vs_persistence'])}** | {pct(s['forecast']['skill_vs_climatology'])} |")
    w("")
    w(f"![Forecast error by month]({fc['figures']['forecast_mae_by_month']})")
    w(f"![Forecast vs actual]({fc['figures']['forecast_scatter']})")
    w("")
    w(f"- The day-ahead forecast beats both naive references in every month: overall its error is "
      f"{pct(a['forecast']['skill_vs_persistence'])} lower than \"tomorrow = today\".")
    w(f"- The monsoon is the hard part: the error roughly triples ({dr['forecast']['mae_kwh']:.2f} → "
      f"{mo['forecast']['mae_kwh']:.2f} kWh/day), but the forecast keeps its lead.")
    w("- *Caveat:* \"actual\" comes from ERA5 reanalysis, not a pyranometer on site, and both sides use the "
      "same physics, so this measures the *weather forecast's* skill for this plant, not model error.")
    w("")

    # 7 ---------------------------------------------------------------- limits
    w("## 7. Limitations")
    w("")
    w("- Inverter output is simulated (real weather, physics, injected faults), so detection numbers "
      "describe this simulator; section 5 shows how they move with its settings.")
    w("- All 8 benchmark seeds share one month of weather at one site; seasons and climates are untested "
      "for detection (the forecast study covers a full year at one site).")
    w("- Model settings were chosen on the same seeds they're scored on (FINDINGS §1), a mild optimism.")
    w("")
    return "\n".join(lines) + "\n"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--report", action="store_true", help="only rewrite REPORT.md from existing results")
    args = p.parse_args()
    if not args.report:
        from . import eda, forecast_skill, model_stats, sensitivity
        print("model statistics..."); model_stats.main()
        print("exploratory analysis..."); eda.main()
        print("sensitivity sweep..."); sensitivity.main()
        print("forecast skill..."); forecast_skill.main()
    (ROOT / "REPORT.md").write_text(report(), encoding="utf-8")
    print(f"wrote {ROOT / 'REPORT.md'}")


if __name__ == "__main__":
    main()
